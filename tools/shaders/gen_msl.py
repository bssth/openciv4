#!/usr/bin/env python3
"""Translates the renderer's HLSL (embedded in the C++ sources) to Metal for macOS.

HLSL -> SPIR-V with glslang, SPIR-V -> MSL with spirv-cross, written to
src/render/MslShaders.inc, which is checked in: building the game needs neither tool.
Run this after changing a shader:  python3 tools/shaders/gen_msl.py
With --check nothing is written: it fails when the checked-in file is not what the tools give now.

Resources keep their register numbers, which is what SDL's Metal backend expects
(SDL_gpu.h): [[texture(n)]]/[[sampler(n)]] pairs, [[buffer(n)]] uniforms, storage
buffers after the uniforms.
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src/render/MslShaders.inc"


def literal(path, name):
    text = (ROOT / path).read_text(encoding="utf-8")
    m = re.search(name + r'\[\] = R"hlsl\((.*?)\)hlsl"', text, re.S)
    if not m:
        sys.exit(f"{name} not found in {path}")
    return m.group(1)


FRAME = literal("src/render/Renderer.h", "kFrameConstantsHlsl")
SOURCES = {
    "model.hlsl": FRAME + literal("src/render/Renderer.cpp", "kShaderBody"),
    "overlay.hlsl": literal("src/render/Renderer.cpp", "kOverlayHlsl"),
    "terrain.hlsl": FRAME + literal("src/render/MapView.cpp", "kTerrainHlsl"),
}
# (file, entry point, stage, uniform buffers: storage buffers come after them)
ENTRIES = [
    ("model.hlsl", "VSMain", "vert", 3),
    ("model.hlsl", "PSMain", "frag", 2),
    ("overlay.hlsl", "VSOverlay", "vert", 2),
    ("overlay.hlsl", "PSOverlay", "frag", 2),
    ("terrain.hlsl", "VSTerrain", "vert", 2),
    ("terrain.hlsl", "PSTerrain", "frag", 2),
]


def run(*args):
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"{' '.join(map(str, args))}\n{r.stdout}\n{r.stderr}")
    return r.stdout


def translate(tmp, file, entry, stage, uniforms):
    hlsl = tmp / f"{entry}.hlsl"
    spv = tmp / f"{entry}.spv"
    hlsl.write_text(SOURCES[file], encoding="utf-8")
    space = "space1" if stage == "vert" else "space3"
    run("glslang", "-D", "-V", "--hlsl-iomap", "--hlsl-offsets", f"-DUNIFORMS={space}", "-S", stage, "-e", entry,
        "--source-entrypoint", entry, "-o", spv, hlsl)
    msl = run("spirv-cross", spv, "--msl", "--msl-version", "20100", "--msl-decoration-binding", "--stage", stage, "--entry", entry)
    # HLSL gives storage buffers a t register; SDL binds them right after the uniform buffers.
    slot = iter(range(uniforms, 14))
    return re.sub(r"(const device \S+ \S+ )\[\[buffer\(\d+\)\]\]", lambda m: f"{m.group(1)}[[buffer({next(slot)})]]", msl)


def finish(out_path, text):
    """Writes the generated file, or with --check compares it with the one checked in."""
    if "--check" not in sys.argv[1:]:
        out_path.write_text(text, encoding="utf-8")
        return
    name = out_path.relative_to(ROOT).as_posix()
    if not out_path.exists() or out_path.read_text(encoding="utf-8") != text:
        sys.exit(f"{name} is not what the shaders in the sources translate to now: "
                 f"run python3 tools/shaders/{Path(sys.argv[0]).name} and commit the result")
    print(name, "is up to date")


def main():
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d)
        out = ["// Generated by tools/shaders/gen_msl.py from the renderer's HLSL. Do not edit.\n"]
        for file, entry, stage, uniforms in ENTRIES:
            msl = translate(tmp, file, entry, stage, uniforms)
            print(file, entry, len(msl), "bytes")
            out.append(f'{{ "{file}", "{entry}", R"msl({msl})msl" }},\n')
    finish(OUT, "".join(out))


if __name__ == "__main__":
    main()
